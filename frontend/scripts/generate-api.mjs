import { spawnSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const cwd = fileURLToPath(new URL("../", import.meta.url));
// Do not pass local runtime policy/secrets to the offline schema exporter.
const env = Object.fromEntries(Object.entries(process.env).filter(([key]) =>
  !/^(API_|HEPHAISTOS_|UPLOAD_|STORAGE_|GENERATION_|QUEUE_|GPU_|JOB_|WORKER_|IDOL_|MODEL_|DISPATCH_|LOGS_|ENABLE_FAKE_ADAPTER$)/.test(key)
));
const result = spawnSync("uv", ["run", "--frozen", "--project", "../backend", "python", "../backend/scripts/export_openapi.py"], { cwd, env, encoding: "utf8" });
if (result.status !== 0) {
  process.stderr.write(result.stderr || "OpenAPI export failed\n");
  process.exit(1);
}
const types = "// Generated by npm run api:generate. Do not edit.\n" + astToString(await openapiTS(JSON.parse(result.stdout)));
const path = new URL("../src/lib/api/schema.d.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (await readFile(path, "utf8").catch(() => "") !== types) {
    console.error("API types are stale. Run npm run api:generate.");
    process.exit(1);
  }
  console.log("API types match the backend OpenAPI contract.");
} else {
  await writeFile(path, types);
  console.log("API types generated offline.");
}
